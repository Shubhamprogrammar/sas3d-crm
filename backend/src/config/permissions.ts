const SETS = Object.fromEntries(
  Object.entries(MATRIX).map(([role, perms]) => [role, new Set<Permission>(perms)]),
) as Record<Role, Set<Permission>>;

export const hasPermission = (role: Role, permission: Permission) => SETS[role].has(permission);
export const permissionsFor = (role: Role): Permission[] => [...SETS[role]];
/** Roles whose visibility of leads, projects and other records is not limited to their own assignments. */
export const hasGlobalScope = (role: Role) => role === "SUPER_ADMIN" || role === "ADMIN";
export const canManageRole = (actor: Role, target: Role) =>
  actor === "SUPER_ADMIN" || (actor === "ADMIN" && target !== "SUPER_ADMIN" && target !== "ADMIN");
export const permissionMatrix = () => MATRIX;
